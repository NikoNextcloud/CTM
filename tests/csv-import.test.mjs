import assert from 'node:assert/strict';
import {parseCsv,csvEscape} from '../src/lib/import-csv.ts';
const good='\uFEFFname;eik;address;status\r\n"ТЕСТ Фирма, ЕООД";000000001;"Тест; адрес";active\r\n';
const result=parseCsv(good,'companies');
assert.equal(result.issues.length,0);
assert.equal(result.rows.length,1);
assert.equal(result.rows[0].eik,'000000001');
assert.equal(result.rows[0].address,'Тест; адрес');
assert.match(csvEscape(' \t=HYPERLINK("http://invalid")'),/^"' /);
assert.equal(parseCsv('name;eik;address;status\nРеална фирма;123456789;;active','companies').issues.length,0);
assert.equal(parseCsv('name;eik;address;status\nДруга фирма;123456789;;inactive','companies').issues.length,0);
assert.ok(parseCsv('name;eik;address;status\n"ТЕСТ фирма;000000001;;active','companies').issues.length>0);
assert.ok(parseCsv('name;eik;address;status\nТЕСТ фирма;000000001;x;active;extra','companies').issues.length>0);
assert.ok(parseCsv('name;eik;address;status\nНевалидна фирма;12345678;;active','companies').issues.length>0);
assert.equal(parseCsv('company_eik;full_name;job_title;reference_code\n123456789;Иван Иванов Иванов;Работник;','employees').issues.length,0);
console.log('CSV parser: real names, EIK shape, quotes, UTF8, formulas and row limits PASSED.');
